  function mirror(rows) {
    return rows.map((row) => row.split("").reverse().join(""));
  }

  function framesFor(name) {
    const head = HEADS[name];
    const body = BODIES[PEOPLE[name].body];
    const out = {};
    for (const dir of ["down", "up", "left"]) {
      const h = head[dir];
      const b = body[dir] || body.down;
      const stand = h.concat(b[0]);
      const stepA = h.concat(b[1]);
      const stepB = b[2] ? h.concat(b[2]) : mirror(stepA);
      out[dir] = [stand, stepA, stepB];
    }
    return out;
  }

